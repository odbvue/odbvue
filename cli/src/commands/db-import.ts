import { Command } from 'commander';
import {
  logger,
  rootDir,
  path,
  existsSync,
  readFileSync,
  writeFileSync,
  mkdirSync,
  readdirSync,
} from '../utils.js';

// ============================================================================
// Types
// ============================================================================

type ColumnInfo = {
  name: string;
  description?: string;
  type: string;
  default: string | null;
  required: boolean;
  identity: boolean;
};

type TableInfo = {
  name: string;
  description?: string;
  columns: ColumnInfo[];
  primary_key: string[];
  unique?: string[][];
  indexes?: string[][] | null;
  checks?: Array<{
    column: string;
    values: string[];
  }> | null;
  foreignKeys?: Array<{
    name: string;
    column: string;
    referenceTable: string;
    referenceColumn: string;
  }> | null;
};

type UpsertInfo = {
  table: string;
  key: string | string[];
  rows: Record<string, unknown>[];
};

type MethodParamInfo = {
  name: string;
  direction: 'IN' | 'OUT' | 'IN OUT';
  type: string;
  description?: string;
};

type MethodInfo = {
  name: string;
  type: 'PROCEDURE' | 'FUNCTION';
  returnType?: string;
  params?: MethodParamInfo[];
  body?: string;
  description?: string;
  authid?: string;
};

type ServiceInfo = {
  name: string;
  editionable?: boolean;
  authid?: string;
  methods?: MethodInfo[];
};

type SchemaJson = {
  schema: string;
  exported: string;
  tables: TableInfo[];
  upserts?: UpsertInfo[];
  services?: ServiceInfo[];
};

