CREATE TABLE APP_USERS (
  ID NUMBER(19,0) NOT NULL GENERATED BY DEFAULT AS IDENTITY,
  UUID RAW(16) DEFAULT SYS_GUID() NOT NULL,
  USERNAME VARCHAR2(200 CHAR) NOT NULL,
  PASSWORD VARCHAR2(2000 CHAR) NOT NULL,
  FULLNAME VARCHAR2(200 CHAR) NOT NULL,
  STATUS CHAR(1 CHAR) DEFAULT 'A' NOT NULL,
  CREATED TIMESTAMP(6) DEFAULT SYSTIMESTAMP NOT NULL,
  ATTEMPTS NUMBER(19,0) DEFAULT 0 NOT NULL,
  ACCESSED TIMESTAMP(6),
  ATTEMPTED TIMESTAMP(6),
  CONSTRAINT pk_app_users PRIMARY KEY (ID)
);